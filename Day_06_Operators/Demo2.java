public class Demo2 {
    public static void main(String[] args) {
        // Relational operators ( >, <, >= , <= , == , !=);

        int a = 10;
        int b = 20;

        boolean result = a > b; // false
        System.out.println("a > b: " + result);
        result = a < b; // true
        System.out.println("a < b: " + result);
        result = a >= b; // false
        System.out.println("a >= b: " + result);
        result = a <= b; // true
        System.out.println("a <= b: " + result);
        result = a == b; // false
        System.out.println("a == b: " + result);
        result = a != b; // true
        System.out.println("a != b: " + result);
        
    }
}
